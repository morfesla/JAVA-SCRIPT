// 1. Você define os valores de A e B aqui para testar:
let A = 5;
let B = 5;

// Criamos a variável C sem valor nenhum por enquanto
let C;

// 2. A estrutura condicional (O "Se" e "Caso contrário")
if (A === B) {
    C = A + B; // Se forem iguais, soma
} else {
    C = A * B; // Se forem diferentes, multiplica
}

// 3. Mostra o resultado no terminal
console.log("O resultado da variável C é:", C);